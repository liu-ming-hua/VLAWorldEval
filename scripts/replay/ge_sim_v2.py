#!/usr/bin/env python3
"""Full-action autoregressive replay on an official GE-Sim 2.0 episode."""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

DEFAULT_EPISODE = ROOT / "third_party/ge-sim-v2/assets/demo_000"
DEFAULT_OUTPUT = ROOT / "results/official_autoregressive/ge_sim_v2_demo_000"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--episode", type=Path, default=DEFAULT_EPISODE)
    parser.add_argument("--server", default="http://127.0.0.1:9000")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--chunk-size", type=int, default=25)
    parser.add_argument(
        "--max-actions",
        type=int,
        default=0,
        help="Run only the first N recorded actions; 0 means the full episode.",
    )
    parser.add_argument("--fps", type=int, default=16)
    parser.add_argument(
        "--conditioning",
        choices=("action", "episode"),
        default="episode",
        help="Official replay uses episode; action is for closed-loop policy tests.",
    )
    parser.add_argument("--timeout", type=float, default=600.0)
    args = parser.parse_args()
    from vlaworldeval.paths import fresh_output_path
    args.output = fresh_output_path(ROOT, args.output)

    episode = args.episode.resolve()
    actions_path = episode / "actions_0.npy"
    task_path = episode / "task.txt"
    if not episode.is_dir() or not actions_path.is_file():
        raise FileNotFoundError(f"GE-Sim episode bundle is incomplete: {episode}")
    actions = np.asarray(np.load(actions_path), dtype=np.float32)
    if actions.ndim != 2 or actions.shape[1] != 16:
        raise ValueError(f"GE-Sim official actions must be [T,16], got {actions.shape}")
    if args.max_actions > 0:
        actions = actions[: args.max_actions]
    task = task_path.read_text().strip() if task_path.exists() else ""

    from adapters.world_models.ge_sim_v2 import GESimV2Adapter
    args.output.mkdir(parents=True, exist_ok=False)
    adapter = GESimV2Adapter(
        server_url=args.server,
        episode_path=episode,
        repo_path=ROOT / "third_party/ge-sim-v2",
        chunk_size=args.chunk_size,
        compress_actions=False,
        conditioning=args.conditioning,
        task=task,
        timeout=args.timeout,
    )
    adapter.reset(episode)
    videos: list[np.ndarray] = []
    states: list[np.ndarray] = []
    chunks = []
    for chunk_index, start in enumerate(range(0, len(actions), args.chunk_size)):
        chunk = actions[start : start + args.chunk_size]
        t0 = time.time()
        generated = np.asarray(adapter.rollout(chunk))  # [T,V,H,W,3]
        elapsed = time.time() - t0
        videos.append(np.concatenate([generated[:, i] for i in range(generated.shape[1])], axis=2))
        if adapter.last_state is not None:
            states.append(np.asarray(adapter.last_state, dtype=np.float32))
        np.save(args.output / f"actions_chunk_{chunk_index:03d}.npy", chunk)
        chunks.append({
            "chunk_index": chunk_index,
            "source_start": start,
            "action_shape": list(chunk.shape),
            "video_shape": list(generated.shape),
            "state_shape": None if adapter.last_state is None else list(np.asarray(adapter.last_state).shape),
            "inference_seconds": elapsed,
        })
        print(f"[ge-sim] chunk={chunk_index} actions={start}:{start + len(chunk)} time={elapsed:.2f}s", flush=True)

    adapter.env.save_video(args.output / "rollout_long.mp4", fps=args.fps)
    np.save(args.output / "actions_all.npy", actions)
    if states:
        np.save(args.output / "state_all.npy", np.concatenate(states, axis=0))
    metadata = {
        "format_version": 1,
        "model": "GE-Sim 2.0",
        "protocol": "official GE-Sim episode replay with full action autoregression",
        "source": str(episode),
        "task": task,
        "conditioning": args.conditioning,
        "ground_truth_rgb_used": False,
        "rgb_conditioning_source": (
            "initial cur_head/cur_left/cur_right only; future RGB is generated by GE-Sim"
        ),
        "memory_source": "generated_frames (not recorded future RGB)",
        "action_representation": "official G01/OmniPicker absolute joint targets [L7, Lgrip, R7, Rgrip]",
        "action_shape": list(actions.shape),
        "action_chunk_size": args.chunk_size,
        "compress_actions": False,
        "num_action_chunks": len(chunks),
        "state_file": "state_all.npy" if states else None,
        "state_representation": "GE-Sim Pose-Expert predicted state, WM layout [L7, Lgrip, R7, Rgrip]" if states else None,
        "video_file": "rollout_long.mp4",
        "video_fps": args.fps,
        "chunks": chunks,
    }
    args.output.joinpath("metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    adapter.close()
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
